"""Generate strict Pydantic boundary models directly from the reviewed schema."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / 'specs/cvd-studio/schemas/cvd-studio.schema.json').read_text())
classes = {}

def annotation(s, name):
    if '$ref' in s:
        return s['$ref'].split('/')[-1]
    if 'const' in s:
        return f'Literal[{s["const"]!r}]'
    if 'enum' in s:
        return 'Literal[' + ', '.join(repr(v) for v in s['enum']) + ']'
    for branch in ('oneOf', 'anyOf'):
        if branch in s:
            return ' | '.join(annotation(v, name + str(i)) for i,v in enumerate(s[branch]))
    t = s.get('type')
    if t == 'object':
        classes[name] = s
        return name
    if t == 'array':
        a = 'list[' + annotation(s['items'], name + 'Item') + ']'
    else:
        a = {'number':'float', 'integer':'int', 'string':'str', 'boolean':'bool', 'null':'None'}[t]
    limits = {'minimum':'ge', 'maximum':'le', 'exclusiveMinimum':'gt', 'exclusiveMaximum':'lt',
              'minLength':'min_length', 'maxLength':'max_length', 'minItems':'min_length', 'maxItems':'max_length', 'pattern':'pattern'}
    args = [f'{dest}={s[src]!r}' for src,dest in limits.items() if src in s]
    return f'Annotated[{a}, Field({", ".join(args)})]' if args else a

aliases = []
for name,s in schema['$defs'].items():
    if s.get('type') == 'object':
        classes[name] = s
    else:
        aliases.append((name,s))
out = ['# Generated by scripts/generate_models.py; do not edit.',
       'from __future__ import annotations', 'from typing import Annotated, Literal, Union',
       'from pydantic import BaseModel, ConfigDict, Field',
       'class StrictModel(BaseModel):',
       '    model_config = ConfigDict(extra="forbid", strict=True, allow_inf_nan=False)']
# Alias annotations containing forward references need string operands inside typing.Union.
for name,s in aliases:
    if 'oneOf' in s or 'anyOf' in s:
        refs = [v['$ref'].split('/')[-1] for v in s.get('oneOf',s.get('anyOf',[]))]
        out.append(f'{name} = Union[' + ', '.join(repr(v) for v in refs) + ']')
    else:
        out.append(f'{name} = {annotation(s,name)}')
done = set()
while set(classes) - done:
    for name in list(classes):
        if name in done: continue
        s = classes[name]
        out += [f'class {name}(StrictModel):']
        out += [f'    {key}: {annotation(value,name+key.title())}' for key,value in s['properties'].items()]
        done.add(name)
out.append('for _model in list(globals().values()):\n    if isinstance(_model, type) and issubclass(_model, StrictModel):\n        _model.model_rebuild()')
target = ROOT / 'apps/api/src/cvd_studio/api/models.py'
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text('\n'.join(out)+'\n', encoding='utf-8', newline='\n')
print(f'Generated {len(done)} strict models')
